// Escape characters that have special meaning inside an HTML attribute
// or text node so a value can be safely interpolated into a template
// literal that goes into innerHTML.

export function escapeHtml(s: string): string {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
